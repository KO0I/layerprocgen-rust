import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {mkdir,readFile,writeFile} from 'node:fs/promises';
import {spawnSync} from 'node:child_process';
import path from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
const args=process.argv.slice(2);
const option=(name,fallback)=>{const i=args.indexOf(name);return i<0?fallback:args[i+1];};
const rfl=path.resolve(option('--rfl',path.join(root,'../rasd-fastwalker-league-js')));
const checking=args.includes('--check');
const frozen=path.join(root,'fixtures/rfl-route');
const output=path.resolve(option('--output',path.join(root,checking?'target/rfl-route-check':'fixtures/rfl-route')));
assert(!checking || output!==frozen,'--check must not overwrite the frozen fixture');
const load=name=>import(pathToFileURL(path.join(rfl,name)));
const sha=data=>createHash('sha256').update(data).digest('hex');
await load('dist/climate/terrain.js');
const {flightSnapshot}=await load('dist/climate/flight-snapshot.js');
const {makeClimateBody}=await load('dist/climate-world.js');
const {streamRegion,generateTile}=await load('dist/surface-stream-core.js');
const {groundElevation}=await load('dist/world-core.js');
const {basinData}=await load('dist/ocean-basins-data.js');
const settings={...globalThis.ExoTerrain.defaults,seed:1610};
const snapshot=flightSnapshot({terrain:globalThis.ExoTerrain.generate(settings,64),settings,palette:globalThis.ExoTerrain.palette,selection:{planet:'temperate',atmosphere:'nitrogen'},atmosphere:{colors:['#ffffff','#3388bb']},name:'Terrain worker Quick fixture'});
const payload=JSON.stringify(snapshot,(_,value)=>ArrayBuffer.isView(value)?Array.from(value):value);
const snapshotHash=sha(payload);
assert.equal(snapshotHash,'e9225cfd01683391d78899510e89d213351d563184dc77d95c9b27d2dee4db0a','fixed original RFL climate export');
const body={...makeClimateBody(snapshot),spin:0,tilt:0};
const frame={center:[0.9745928472107236,0.2068482987815016,-0.08592184505056787],right:[-0.017682468323930285,0.45346334155548,0.8910995052065237],forward:[0.22328482366624994,-0.8669398936238526,0.4455997176433069]};
const dot=(a,b)=>a.reduce((s,v,i)=>s+v*b[i],0);
const direction=(x,z)=>{const q=frame.center.map((v,i)=>v+(frame.right[i]*x+frame.forward[i]*z)/body.radius);const n=Math.hypot(...q);return q.map(v=>v/n);};
const region=streamRegion(body,frame.center.map(v=>v*(body.radius+2)));
const buildings=region.tiles.flatMap(tile=>generateTile(body,tile,{buildingsOnly:true}));
const ids=['0:21:21:0:0','0:18:22:0:4'];
const sites=ids.map(id=>{
 const site=buildings.find(s=>s.id===id);assert(site,`existing RFL site ${id}`);
 const chart={x:body.radius*dot(site.up,frame.right)/dot(site.up,frame.center),z:body.radius*dot(site.up,frame.forward)/dot(site.up,frame.center)};
 return {...site,chart};
});
assert.equal(buildings.length,2,'ordinary fixed region contains the selected buildings');
const heights=Buffer.alloc(snapshot.heights.length*4);snapshot.heights.forEach((h,i)=>heights.writeFloatLE(h,i*4));
const grid={width:129,rows:65,spacing:2,minX:-128,minZ:-64};
const ground=[];for(let z=0;z<grid.rows;z++)for(let x=0;x<grid.width;x++)ground.push(groundElevation(body,direction(grid.minX+x*grid.spacing,grid.minZ+z*grid.spacing)));
const gridBytes=Buffer.alloc(ground.length*8);ground.forEach((h,i)=>gridBytes.writeDoubleLE(h,i*8));
const sources=['dist/climate/terrain.js','dist/climate/flight-snapshot.js','dist/climate-world.js','dist/climate-sample.js','dist/world-core.js','dist/surface-stream-core.js','dist/ground-scale.js','dist/settlements.js','native/world/src/rocky.rs'];
const sourceHashes=Object.fromEntries(await Promise.all(sources.map(async f=>[f,sha(await readFile(path.join(rfl,f)))])));
const revision=spawnSync('git',['rev-parse','HEAD'],{cwd:rfl,encoding:'utf8'});assert.equal(revision.status,0);
const manifest={schema:1,snapshotSha256:snapshotHash,sourceCommit:revision.stdout.trim(),sourceHashes,settings,units:'RFL world units; snapshot conversion is metres / 6371',radius:body.radius,seaLevel:body.seaLevel,seed:body.seed,width:snapshot.width,rows:snapshot.rows,frame,sites,grid,heightsSha256:sha(heights),basinsSha256:sha(Uint8Array.from(basinData)),groundSha256:sha(gridBytes),sampling:'RFL SurfaceTerrain::elevation for planning; JS groundElevation samples for independent comparison',limitations:['building centers, not entrance portals','bounded gnomonic chart, not global spherical routing','terrain-only constraints; building volumes are not obstacles']};
await mkdir(output,{recursive:true});
await writeFile(path.join(output,'manifest.json'),JSON.stringify(manifest,null,2)+'\n');
await writeFile(path.join(output,'heights.f32'),heights);
await writeFile(path.join(output,'basins.u8'),Uint8Array.from(basinData));
await writeFile(path.join(output,'ground.f64'),gridBytes);
const bridge=path.join(root,'target/rfl-route-bridge');await mkdir(path.join(bridge,'src'),{recursive:true});
const toml=`[package]\nname="rfl-route-checkpoint"\nversion="0.0.0"\nedition="2024"\n[workspace]\n[dependencies]\nlayerprocgen={path=${JSON.stringify(root)}}\nrfl-world={path=${JSON.stringify(path.join(rfl,'native/world'))}}\nserde_json="=1.0.149"\n`;
await writeFile(path.join(bridge,'Cargo.toml'),toml);
await writeFile(path.join(bridge,'src/main.rs'),await readFile(path.join(root,'tools/rfl-route/main.rs')));
const run=spawnSync('cargo',['run','--offline','--release','--manifest-path',path.join(bridge,'Cargo.toml'),'--',output],{cwd:root,stdio:'inherit'});
assert.equal(run.status,0,'actual RFL Rust sampler checkpoint');
const route=JSON.parse(await readFile(path.join(output,'route.json'),'utf8'));
const webData=JSON.stringify({...route,manifest,ground},null,0)+'\n';
if(checking) {
 const recorded=JSON.parse(await readFile(path.join(frozen,'manifest.json'),'utf8'));
 assert.deepEqual(JSON.parse(JSON.stringify({...manifest,sourceCommit:null})),{...recorded,sourceCommit:null},'fixed climate input and source hashes reproduce');
 for(const file of ['heights.f32','basins.u8','ground.f64','route.json']) assert.deepEqual(await readFile(path.join(output,file)),await readFile(path.join(frozen,file)),`reproducible ${file}; use the recorded RFL source revision`);
 const reproducedWeb=JSON.stringify({...route,manifest:{...manifest,sourceCommit:recorded.sourceCommit},ground},null,0)+'\n';
 assert.equal(reproducedWeb,await readFile(path.join(root,'web/route-checkpoint.json'),'utf8'),'viewer data matches regenerated native route');
 if(manifest.sourceCommit!==recorded.sourceCommit) console.log(`RFL HEAD is ${manifest.sourceCommit}; recorded source hashes and all output bytes match the frozen checkpoint.`);
} else await writeFile(path.join(root,'web/route-checkpoint.json'),webData);
console.log(`PASS fixed climate ${snapshotHash}; sites ${ids.join(' -> ')}; actual Rust sampler path exported`);
